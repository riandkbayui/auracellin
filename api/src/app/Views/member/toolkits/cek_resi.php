<h3 class="text-primary">🔍 Cara Memastikan Status Pengiriman Produk</h3>
<p>Untuk memastikan status pengiriman produk Anda telah diproses dan sedang dikirim, silakan ikuti langkah-langkah berikut:</p>

<ol>
  <li>
    <b>Buka link berikut:</b><br>
    🔗 <a href="https://distributorbgn.com" target="_blank">https://distributorbgn.com</a>
  </li>
  <li>
    <b>Cara Pengecekan Resi:</b>

    <h4 class="text-primary">✅ Langkah Umum:</h4>
    <ul>
      <li>Ketik <b>nama Anda</b> pada kolom pencarian.</li>
      <li>Klik ikon panah di kiri (dekat angka 1) untuk melihat data penerima.</li>
    </ul>

    <h4 class="text-primary">🚚 Jika menggunakan JNE:</h4>
    <ul>
      <li>Klik ikon kaca pembesar di samping nomor resi.</li>
      <li>Klik tombol <b>"Cek Data Pengiriman"</b> untuk melihat status paket.</li>
    </ul>

    <h4 class="text-primary">🚛 Jika menggunakan JNT Cargo:</h4>
    <ul>
      <li>Klik kotak kuning untuk menyalin nomor resi.</li>
      <li>Klik ikon kaca pembesar di samping nomor resi.</li>
      <li>Tempel nomor resi yang sudah disalin.</li>
      <li>Klik lagi ikon kaca pembesar.</li>
      <li>
        Masukkan <b>4 digit terakhir nomor HP pengirim</b> (<code class="text-primary">1157</code>) atau nomor HP penerima.
      </li>
    </ul>
  </li>
</ol>

<p><b>Catatan:</b> Jika Anda mengalami kendala saat pengecekan, silakan hubungi tim support kami melalui aplikasi.</p>

